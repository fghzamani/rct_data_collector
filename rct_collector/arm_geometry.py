"""Exact arm geometry from the URDF collision shapes, by forward kinematics.

Shared by the supervisor's data audit (per-probe footprint coverage) and
src/rct_data_collector/tools/arm_footprint_fk.py (envelope computation). The URDF is generated by
xacro with the arguments the simulation launches TIAGo with; FK reproduces the
link poses Gazebo records in telemetry to 0 mm median (10 mm max, timing skew).
"""
from __future__ import annotations

import math
import os
import re
import struct
import subprocess
import sys
import xml.etree.ElementTree as ET

import numpy as np

XACRO = "/opt/ros/humble/share/tiago_description/robots/tiago.urdf.xacro"
SHARE = "/opt/ros/humble/share"
BASE = "base_footprint"
ARM_LINK_RE = re.compile(r"^(arm_\d_link|arm_tool_link|wrist_ft(_tool)?_link|gripper_.*)$")


# ── geometry helpers ─────────────────────────────────────────────────────────
def rpy_matrix(r, p, y):
    cr, sr, cp, sp, cy, sy = math.cos(r), math.sin(r), math.cos(p), math.sin(p), math.cos(y), math.sin(y)
    return np.array([[cy * cp, cy * sp * sr - sy * cr, cy * sp * cr + sy * sr],
                     [sy * cp, sy * sp * sr + cy * cr, sy * sp * cr - cy * sr],
                     [-sp, cp * sr, cp * cr]])


def tf(xyz=(0, 0, 0), rpy=(0, 0, 0)):
    T = np.eye(4)
    T[:3, :3] = rpy_matrix(*rpy)
    T[:3, 3] = xyz
    return T


def axis_angle(axis, a):
    axis = np.asarray(axis, float)
    axis = axis / np.linalg.norm(axis)
    K = np.array([[0, -axis[2], axis[1]], [axis[2], 0, -axis[0]], [-axis[1], axis[0], 0]])
    T = np.eye(4)
    T[:3, :3] = np.eye(3) + math.sin(a) * K + (1 - math.cos(a)) * K @ K
    return T


def hull3d(P):
    """Reduce a vertex cloud to its 3-D convex hull vertices (projection of a
    convex hull = convex hull of the projection, so nothing is lost)."""
    try:
        from scipy.spatial import ConvexHull
        return P[ConvexHull(P).vertices]
    except Exception:   # noqa: BLE001
        return P


def convex_hull2d(pts):
    pts = sorted(set(map(tuple, np.round(pts, 5))))
    if len(pts) <= 2:
        return np.array(pts, float)

    def cross(o, a, b):
        return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])
    lo, up = [], []
    for p in pts:
        while len(lo) >= 2 and cross(lo[-2], lo[-1], p) <= 0:
            lo.pop()
        lo.append(p)
    for p in reversed(pts):
        while len(up) >= 2 and cross(up[-2], up[-1], p) <= 0:
            up.pop()
        up.append(p)
    return np.array(lo[:-1] + up[:-1], float)


def simplify_outward(poly, max_vertices=16):
    """Fewer vertices WITHOUT shrinking: repeatedly drop the vertex whose
    removal loses the least area. Dropping a convex-hull vertex can only cut
    area, so instead each step replaces vertices (a, b, c) by the intersection
    of edges (prev(a), a) and (c, next(c)) only when that grows area minimally;
    simplest robust option here: keep the hull, merge near-collinear vertices."""
    out = list(poly)
    while len(out) > max_vertices:
        n = len(out)
        best, bi = None, None
        for i in range(n):
            a, b, c = np.array(out[i - 1]), np.array(out[i]), np.array(out[(i + 1) % n])
            area = abs((b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0])) / 2
            if best is None or area < best:
                best, bi = area, i
        # removing b cuts a triangle of `best` area: push a and c outward so the
        # new edge a'-c' still contains b (offset the chord by b's distance).
        a, b, c = np.array(out[bi - 1]), np.array(out[bi]), np.array(out[(bi + 1) % n])
        d = c - a
        nrm = np.array([d[1], -d[0]]) / (np.linalg.norm(d) + 1e-12)
        if np.dot(nrm, b - a) < 0:
            nrm = -nrm
        h = np.dot(nrm, b - a)
        out[bi - 1] = tuple(a + nrm * h)
        out[(bi + 1) % n] = tuple(c + nrm * h)
        del out[bi]
        out = list(convex_hull2d(np.array(out)))
    return np.array(out, float)


def poly_signed_dist(poly, pts):
    """Signed distance of each point to the polygon boundary (+ = outside)."""
    from matplotlib.path import Path
    pts = np.atleast_2d(pts)
    a = poly
    b = np.roll(poly, -1, 0)
    ab = b - a
    d = np.full(len(pts), np.inf)
    for i in range(len(a)):
        t = np.clip(((pts - a[i]) @ ab[i]) / (ab[i] @ ab[i]), 0, 1)
        d = np.minimum(d, np.linalg.norm(a[i] + t[:, None] * ab[i] - pts, axis=1))
    inside = Path(poly).contains_points(pts)
    return np.where(inside, -d, d)


def octagon(r, n=24):
    a = np.linspace(0, 2 * np.pi, n, endpoint=False)
    return np.stack([r * np.cos(a), r * np.sin(a)], 1)


# ── meshes ───────────────────────────────────────────────────────────────────
def resolve(fn):
    if fn.startswith("package://"):
        pkg, rel = fn[len("package://"):].split("/", 1)
        return os.path.join(SHARE, pkg, rel)
    if fn.startswith("file://"):
        return fn[len("file://"):]
    return fn


def load_mesh(path):
    if path.lower().endswith(".stl"):
        raw = open(path, "rb").read()
        if raw[:5].lower() == b"solid" and b"facet" in raw[:400]:
            v = re.findall(rb"vertex\s+(\S+)\s+(\S+)\s+(\S+)", raw)
            return np.array(v, float)
        n = struct.unpack("<I", raw[80:84])[0]
        arr = np.frombuffer(raw[84:84 + n * 50], dtype=np.dtype([
            ("n", "<f4", 3), ("v", "<f4", (3, 3)), ("a", "<u2")]))
        return arr["v"].reshape(-1, 3).astype(float)
    s = open(path).read()
    # PAL's .dae collision meshes carry their vertices in the link frame (the
    # Y_UP tag is not applied by Gazebo/ROS; checked against the joint offsets).
    unit = re.search(r'<unit[^>]*meter="([^"]+)"', s)
    arrs = re.findall(r'<float_array[^>]*id="([^"]*)"[^>]*>([^<]*)</float_array>', s)
    P = [np.array(a.split(), float).reshape(-1, 3) for i, a in arrs if "position" in i.lower()]
    P = np.vstack(P)
    if re.search(r"<matrix", s):
        sys.exit(f"{path}: node transforms in .dae not supported")
    return P * (float(unit.group(1)) if unit else 1.0)


# ── robot model ──────────────────────────────────────────────────────────────
class Robot:
    def __init__(self, urdf_xml: str):
        r = ET.fromstring(urdf_xml)
        self.joints = {}          # child link -> (name, type, parent, T_origin, axis)
        for j in r.findall("joint"):
            o = j.find("origin")
            xyz = [float(v) for v in (o.get("xyz", "0 0 0") if o is not None else "0 0 0").split()]
            rpy = [float(v) for v in (o.get("rpy", "0 0 0") if o is not None else "0 0 0").split()]
            ax = j.find("axis")
            axis = [float(v) for v in ax.get("xyz").split()] if ax is not None else [1, 0, 0]
            self.joints[j.find("child").get("link")] = (
                j.get("name"), j.get("type"), j.find("parent").get("link"), tf(xyz, rpy), axis)
        self.geom = {}            # link -> (M,3) points in the link frame
        for link in r.findall("link"):
            name = link.get("name")
            pts = []
            for col in link.findall("collision"):
                o = col.find("origin")
                xyz = [float(v) for v in (o.get("xyz", "0 0 0") if o is not None else "0 0 0").split()]
                rpy = [float(v) for v in (o.get("rpy", "0 0 0") if o is not None else "0 0 0").split()]
                T = tf(xyz, rpy)
                g = col.find("geometry")[0]
                if g.tag == "box":
                    sx, sy, sz = (float(v) / 2 for v in g.get("size").split())
                    P = np.array([[x, y, z] for x in (-sx, sx) for y in (-sy, sy) for z in (-sz, sz)])
                elif g.tag == "cylinder":
                    rr, L = float(g.get("radius")), float(g.get("length")) / 2
                    a = np.linspace(0, 2 * np.pi, 16, endpoint=False)
                    P = np.vstack([np.stack([rr * np.cos(a), rr * np.sin(a), np.full(16, z)], 1)
                                   for z in (-L, L)])
                elif g.tag == "sphere":
                    rr = float(g.get("radius"))
                    P = np.array([[rr * s * (i == 0), rr * s * (i == 1), rr * s * (i == 2)]
                                  for i in range(3) for s in (-1, 1)])
                elif g.tag == "mesh":
                    P = load_mesh(resolve(g.get("filename")))
                    if g.get("scale"):
                        P = P * np.array([float(v) for v in g.get("scale").split()])
                    P = hull3d(P)
                else:
                    continue
                pts.append((T[:3, :3] @ P.T).T + T[:3, 3])
            if pts:
                self.geom[name] = np.vstack(pts)

    def link_tf(self, link, q, cache):
        if link == BASE:
            return np.eye(4)
        if link in cache:
            return cache[link]
        name, typ, parent, T0, axis = self.joints[link]
        T = self.link_tf(parent, q, cache) @ T0
        v = q.get(name, 0.0)
        if typ in ("revolute", "continuous"):
            T = T @ axis_angle(axis, v)
        elif typ == "prismatic":
            M = np.eye(4)
            M[:3, 3] = np.asarray(axis) * v
            T = T @ M
        cache[link] = T
        return T

    def arm_points(self, q, links=None):
        """{link: (M,3) collision points in base_footprint} for the arm links."""
        cache, out = {}, {}
        for link, P in self.geom.items():
            if links is not None and link not in links:
                continue
            if not ARM_LINK_RE.match(link):
                continue
            T = self.link_tf(link, q, cache)
            out[link] = (T[:3, :3] @ P.T).T + T[:3, 3]
        return out


def load_robot():
    # The sim launches TIAGo with these (TiagoArgs defaults in the launch file);
    # the bare xacro default is pal-hey5, which has no gripper_link.
    xml = subprocess.run(["xacro", XACRO, "end_effector:=pal-gripper", "ft_sensor:=schunk-ft",
                          "wrist_model:=wrist-2017", "arm_type:=tiago-arm", "laser_model:=sick-571",
                          "is_public_sim:=true"],
                         capture_output=True, text=True, check=True).stdout
    return Robot(xml)


